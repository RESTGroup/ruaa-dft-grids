//! Fixed-lane (`f64x8`) helpers shared by the partition kernels.
//!
//! The lane width is deliberately fixed at eight.  On an AVX-512 build this
//! is one vector register, on AVX2 it is two registers, and on the baseline
//! target it is still correct (LLVM may split it further).  There is no
//! runtime dispatcher and no intrinsic in this module.

use lightweight_simd::{Simd, f64x8};

/// Number of grid points in one fixed-array lane.
pub(crate) const LANES: usize = 8;

/// The fixed-array vector type used by every lane kernel.
pub(crate) type V = f64x8;

/// Zero vector.
#[inline(always)]
pub(crate) fn zero() -> V {
    V::zero()
}

/// One vector.
#[inline(always)]
pub(crate) fn one() -> V {
    V::one()
}

/// Broadcast a scalar.
#[inline(always)]
pub(crate) fn splat(value: f64) -> V {
    V::splat(value)
}

/// Classic Becke polynomial `p(x) = 3/2 x - 1/2 x^3`.
#[inline(always)]
pub(crate) fn p(x: V) -> V {
    splat(1.5) * x - splat(0.5) * x * x * x
}

/// `p'(x) = 3/2 (1 - x^2)`.
#[inline(always)]
pub(crate) fn dp(x: V) -> V {
    splat(1.5) - splat(1.5) * x * x
}

/// `p''(x) = -3 x`.
#[inline(always)]
pub(crate) fn ddp(x: V) -> V {
    splat(-3.0) * x
}

/// Hardness-3 switch value.
#[inline(always)]
pub(crate) fn step3(nu: V) -> V {
    p(p(p(nu)))
}

/// Generic-hardness switch value.
#[inline]
pub(crate) fn step_function(mut f: V, hardness: usize) -> V {
    for _ in 0..hardness {
        f = p(f);
    }
    f
}

/// Value and first `nu`-derivative, hardness 3.
#[inline(always)]
pub(crate) fn value_d1_h3(nu: V) -> (V, V) {
    let f0 = nu;
    let f1 = p(f0);
    let f2 = p(f1);
    let f3 = p(f2);
    let df1 = dp(f0);
    let df2 = dp(f1) * df1;
    let df3 = dp(f2) * df2;
    (f3, df3)
}

/// Value and first `nu`-derivative, generic hardness.
#[inline]
pub(crate) fn value_d1(nu: V, hardness: usize) -> (V, V) {
    let mut f = nu;
    let mut df = one();
    for _ in 0..hardness {
        df *= dp(f);
        f = p(f);
    }
    (f, df)
}

/// Value and first `nu`-derivative, dispatching hardness 3.
#[inline]
pub(crate) fn value_d1_any(nu: V, hardness: usize) -> (V, V) {
    if hardness == 3 {
        value_d1_h3(nu)
    } else {
        value_d1(nu, hardness)
    }
}

/// Value and first two `nu`-derivatives, hardness 3.
#[inline(always)]
pub(crate) fn value_d2_h3(nu: V) -> (V, V, V) {
    let f0 = nu;
    let f1 = p(f0);
    let f2 = p(f1);
    let f3 = p(f2);
    let df0 = one();
    let df1 = dp(f0) * df0;
    let df2 = dp(f1) * df1;
    let df3 = dp(f2) * df2;
    let dd1 = ddp(f0) * df0 * df0;
    let dd2 = ddp(f1) * df1 * df1 + dp(f1) * dd1;
    let dd3 = ddp(f2) * df2 * df2 + dp(f2) * dd2;
    (f3, df3, dd3)
}

/// Value and first two `nu`-derivatives, generic hardness.
#[inline]
pub(crate) fn value_d2(nu: V, hardness: usize) -> (V, V, V) {
    let mut f = nu;
    let mut df = one();
    let mut ddf = zero();
    for _ in 0..hardness {
        ddf = ddp(f) * df * df + dp(f) * ddf;
        df *= dp(f);
        f = p(f);
    }
    (f, df, ddf)
}

/// Value and first two `nu`-derivatives, dispatching hardness 3.
#[inline]
pub(crate) fn value_d2_any(nu: V, hardness: usize) -> (V, V, V) {
    if hardness == 3 {
        value_d2_h3(nu)
    } else {
        value_d2(nu, hardness)
    }
}

/// Generating-atom attribution of one lane.
#[derive(Clone, Copy, Debug)]
pub(crate) enum LaneAttrib {
    /// Every point in the lane belongs to the same atom.
    ByAtom(usize),
    /// Per-lane generating atoms.  `usize::MAX` marks a padding point.
    ByGrid([usize; LANES]),
}

impl LaneAttrib {
    /// Build the attribution for the first `len` entries of `parents`.
    ///
    /// The common case (one grid atom per block) takes the scalar branch in
    /// the pair loop; a mixed lane falls back to mask selection.
    #[inline]
    pub(crate) fn from_parents(parents: &[u32], lane: usize, len: usize) -> Self {
        let base = lane * LANES;
        let first = if base < len {
            parents[base] as usize
        } else {
            usize::MAX
        };
        let mut uniform = first != usize::MAX;
        let mut ids = [usize::MAX; LANES];
        for (l, id) in ids.iter_mut().enumerate() {
            let p = base + l;
            if p < len {
                let a = parents[p] as usize;
                *id = a;
                if a != first {
                    uniform = false;
                }
            }
        }
        if uniform {
            Self::ByAtom(first)
        } else {
            Self::ByGrid(ids)
        }
    }

    /// Select `value` on lanes generated by `atom`, `fallback` elsewhere.
    #[inline(always)]
    pub(crate) fn select(self, atom: usize, value: V, fallback: V) -> V {
        match self {
            Self::ByAtom(parent) => {
                if atom == parent {
                    value
                } else {
                    fallback
                }
            }
            Self::ByGrid(ids) => {
                let mask = Simd(ids.map(|a| a == atom));
                value.mask_select(mask, fallback)
            }
        }
    }

    /// Lane mask selecting points generated by `atom`.
    #[inline(always)]
    pub(crate) fn mask(self, atom: usize) -> Simd<bool, LANES> {
        match self {
            Self::ByAtom(parent) => Simd([parent == atom; LANES]),
            Self::ByGrid(ids) => Simd(ids.map(|a| a == atom)),
        }
    }

    /// The generating-atom numerator for one lane, given the per-atom
    /// products `prod`.
    #[inline]
    pub(crate) fn select_product(self, prod: &[V]) -> V {
        match self {
            Self::ByAtom(parent) => {
                if parent < prod.len() {
                    prod[parent]
                } else {
                    zero()
                }
            }
            Self::ByGrid(_ids) => {
                let mut out = zero();
                for (atom, &value) in prod.iter().enumerate() {
                    out = self.select(atom, value, out);
                }
                out
            }
        }
    }
}

/// Number of valid points in `lane` of a block with `len` points.
#[inline(always)]
pub(crate) fn lane_len(len: usize, lane: usize) -> usize {
    (len - lane * LANES).min(LANES)
}

/// Gather the coordinates of one lane, zero-padding past `len`.
#[inline]
pub(crate) fn gather_coords(coords: &[[f64; 3]], lane: usize) -> [V; 3] {
    let base = lane * LANES;
    [
        V::from_fn(|l| coords.get(base + l).map_or(0.0, |point| point[0])),
        V::from_fn(|l| coords.get(base + l).map_or(0.0, |point| point[1])),
        V::from_fn(|l| coords.get(base + l).map_or(0.0, |point| point[2])),
    ]
}

/// Gather one scalar array lane, zero-padding past `len`.
#[inline]
pub(crate) fn gather(values: &[f64], lane: usize) -> V {
    let base = lane * LANES;
    V::from_fn(|l| values.get(base + l).copied().unwrap_or(0.0))
}

/// Store the first `len` lanes of `value` into a contiguous output slice.
#[inline]
pub(crate) fn store(dst: &mut [f64], value: V, len: usize) {
    if len == LANES {
        value.store_slice(dst);
    } else {
        for (d, v) in dst.iter_mut().take(len).zip(value.as_array()) {
            *d = *v;
        }
    }
}

/// Masked absolute-value threshold: `|value| <= threshold`.
#[inline(always)]
pub(crate) fn abs_le(value: V, threshold: f64) -> Simd<bool, LANES> {
    value.abs().simd_le(splat(threshold))
}

/// Mask for an exact-zero, infinite or NaN lane.
#[inline(always)]
pub(crate) fn degenerate(value: V) -> Simd<bool, LANES> {
    let abs = value.abs();
    let zero = abs.simd_eq(splat(0.0));
    let infinite = abs.simd_eq(splat(f64::INFINITY));
    let nan = value.simd_ne(value);
    zero | infinite | nan
}

/// Convert a boolean mask to `1.0`/`0.0`.
#[inline(always)]
pub(crate) fn mask_value(mask: Simd<bool, LANES>) -> V {
    one().mask_select(mask, zero())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixed_lane_size() {
        assert_eq!(std::mem::size_of::<V>(), 64);
        assert_eq!(std::mem::align_of::<V>(), 64);
    }

    #[test]
    fn vector_switch_matches_scalar() {
        for k in 0..10_000 {
            let x = -1.5 + 3.0 * k as f64 / 10_000.0;
            let scalar = crate::partition::becke::switch::step3(x);
            assert_eq!(step3(splat(x))[0].to_bits(), scalar.to_bits());
        }
    }

    #[test]
    fn attribution_selects_mixed_parents() {
        let parents = [0u32, 0, 0, 0, 1, 1, 1, 1];
        let attr = LaneAttrib::from_parents(&parents, 0, 8);
        assert!(matches!(attr, LaneAttrib::ByGrid(_)));
        let value = splat(3.0);
        let fallback = zero();
        let selected = attr.select(0, value, fallback);
        assert_eq!(
            selected.to_array(),
            [3.0, 3.0, 3.0, 3.0, 0.0, 0.0, 0.0, 0.0]
        );
    }
}
