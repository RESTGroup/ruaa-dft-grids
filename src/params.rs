/// Periodic-table period index: 0 = H/He, 1 = Li–Ne, ..., 6 = Fr–Og.
///
/// This is the periodic-row lookup used by the PySCF sizing rules and the
/// pruning ladder rows.  Returns `None` for Z = 0 and Z > 118.
#[must_use]
pub fn period_index(z: u32) -> Option<usize> {
    if !(1..=118).contains(&z) {
        return None;
    }
    Some(
        [2, 10, 18, 36, 54, 86, 118]
            .iter()
            .filter(|&&cut| z > cut)
            .count(),
    )
}

/// Periodic-table row (1 = H/He, 2 = Li–Ne, ..., 7 = Fr–Og).
///
/// [`period_index`] plus one; `None` for Z = 0 and Z > 118.
///
/// ```
/// use ruaa_dft_grids::params::periodic_row;
///
/// assert_eq!(periodic_row(1), Some(1));    // H
/// assert_eq!(periodic_row(6), Some(2));    // C
/// assert_eq!(periodic_row(118), Some(7));  // Og
/// assert_eq!(periodic_row(0), None);
/// ```
#[must_use]
pub fn periodic_row(z: u32) -> Option<u32> {
    period_index(z).map(|period| period as u32 + 1)
}

